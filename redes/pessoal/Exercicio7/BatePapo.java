    private void BtConectarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtConectarActionPerformed
        try {
            porta = Integer.parseInt(TfPorta.getText());
            endereco = InetAddress.getByName(TfEndereco.getText());
            usuario = TfUsuario.getText();

            // Cria o socket
            socket = new MulticastSocket(porta);

            // Entra no grupo multicast
            socket.joinGroup(new InetSocketAddress(endereco, porta),
                    NetworkInterface.getByInetAddress(endereco));

            // Inicia a thread de recebimento
            Thread.startVirtualThread(() -> {
                try {
                    byte[] dados = new byte[128];

                    while (true) {
                        DatagramPacket pacote =
                                new DatagramPacket(dados, dados.length);

                        socket.receive(pacote);

                        String mensagemRecebida =
                                new String(pacote.getData(), 0,
                                        pacote.getLength());

                        if (!mensagemRecebida.contains(usuario)) {
                            TaTexto.append(mensagemRecebida + "\n");
                        }

                        dados = new byte[128];
                    }

                } catch (Exception e) {
                    e.printStackTrace();
                }
            });

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_BtConectarActionPerformed

    private void BtEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtEnviarActionPerformed
        // TODO add your handling code here:
        try {
            mensagem = TfTexto.getText();

            if (mensagem.equalsIgnoreCase("sair")) {
                socket.close();
                System.exit(0);
            }

            mensagem = usuario + " diz: " + mensagem;

            msg = mensagem.getBytes();

            DatagramPacket dgPacket = new DatagramPacket(
                    msg, msg.length, endereco, porta);

            socket.send(dgPacket);

            TfTexto.setText("");

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_BtEnviarActionPerformed

